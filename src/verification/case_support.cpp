void invalid(std::string_view where, const std::string& message) {
    throw std::invalid_argument(std::string(where) + ": " + message);
}

std::string number(double value) {
    if (value == 0) return "0";   // also turns -0 into 0
    char buffer[64];
    const auto [end, error] = std::to_chars(buffer, buffer + sizeof(buffer), value);
    if (error != std::errc{}) throw std::runtime_error("cannot format a number");
    return std::string(buffer, end);
}

void require_finite(std::string_view where, double value, std::string_view what) {
    if (!std::isfinite(value)) invalid(where, std::string(what) + " must be finite");
}

void require_positive(std::string_view where, double value, std::string_view what) {
    if (!std::isfinite(value) || value <= 0) invalid(where, std::string(what) + " must be positive");
}

void require_non_negative(std::string_view where, double value, std::string_view what) {
    if (!std::isfinite(value) || value < 0) invalid(where, std::string(what) + " must not be negative");
}

void require_material_name(std::string_view where, const std::string& name) {
    const auto letter = [](char c) { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z'); };
    bool ok = !name.empty() && letter(name.front());
    for (const char c : name) ok = ok && (letter(c) || (c >= '0' && c <= '9') || c == '_');
    if (!ok)
        invalid(where, "material name '" + name + "' must start with a letter and contain only letters, digits and '_'");
    if (name.starts_with("detector") || name == "vacuum")
        invalid(where, "material name '" + name + "' has a special meaning in the importer (detector*, vacuum)");
}

void require_boundary_condition(std::string_view where, const BoundaryCondition& condition) {
    require_finite(where, condition.value, "the boundary value");
    if (condition.type == MeshProperties::BcType::Robin) {
        if (!condition.alpha) invalid(where, "a Robin condition needs alpha");
        require_non_negative(where, *condition.alpha, "the Robin coefficient alpha");
    } else if (condition.alpha) {
        invalid(where, "only a Robin condition has alpha");
    }
}

std::string surface_name(const BoundaryCondition& condition) {
    switch (condition.type) {
    case MeshProperties::BcType::Dirichlet: return number(condition.value) + "V";
    case MeshProperties::BcType::Neumann: return "D" + number(condition.value);
    case MeshProperties::BcType::Robin: return "R" + number(*condition.alpha) + "," + number(condition.value);
    }
    return {};
}

std::string volume_name(const MeshProperties::Material& material) {
    return material.voltage ? material.name + " " + number(*material.voltage) + "V" : material.name;
}

bool same_condition(const BoundaryCondition& a, const BoundaryCondition& b) {
    return a.type == b.type && a.value == b.value && a.alpha == b.alpha;
}

void add_condition(std::vector<BoundaryCondition>& list, const BoundaryCondition& condition) {
    for (const auto& c : list)
        if (same_condition(c, condition)) return;
    list.push_back(condition);
}

Vec3 as_stored(const Vec3& position) {
    return {static_cast<double>(static_cast<float>(position[0])), static_cast<double>(static_cast<float>(position[1])),
            static_cast<double>(static_cast<float>(position[2]))};
}

std::string geo_header() {
    return "// Generated by poisson_case; mesh sizes are set with gmsh -setnumber <name> <value>.\n"
           "SetFactory(\"OpenCASCADE\");\n"
           "DefineConstant[ h_max = 1, h_min = 0, h_charge = 0, r_fine = 0, r_coarse = 0 ];\n"
           "Mesh.MeshSizeMax = h_max;\n"
           "Mesh.MeshSizeMin = h_min;\n";
}

std::string geo_refinement(const std::vector<Vec3>& points) {
    if (points.empty()) return {};
    std::ostringstream out;
    out << "// A finer mesh around the charges: h_charge within r_fine, growing to h_max at r_coarse.\n"
        << "If (h_charge > 0)\n";
    std::string list;
    for (std::size_t i = 0; i < points.size(); ++i) {
        out << "  refine_" << i << " = newp; Point(refine_" << i << ") = {" << number(points[i][0]) << ", "
            << number(points[i][1]) << ", " << number(points[i][2]) << "};\n";
        list += (i ? ", refine_" : "refine_") + std::to_string(i);
    }
    out << "  Field[1] = Distance;\n"
        << "  Field[1].PointsList = {" << list << "};\n"
        << "  Field[2] = Threshold;\n"
        << "  Field[2].InField = 1;\n"
        << "  Field[2].SizeMin = h_charge;\n"
        << "  Field[2].SizeMax = h_max;\n"
        << "  Field[2].DistMin = r_fine;\n"
        << "  Field[2].DistMax = r_coarse;\n"
        << "  Background Field = 2;\n"
        << "EndIf\n";
    return out.str();
}

void add_to_group(std::vector<PhysicalGroup>& groups, const std::string& name, const std::string& list) {
    for (auto& group : groups)
        if (group.name == name) {
            group.lists.push_back(list);
            return;
        }
    groups.push_back({name, {list}});
}

std::string geo_physicals(const char* kind, const std::vector<PhysicalGroup>& groups) {
    std::ostringstream out;
    for (const auto& group : groups) {
        out << "Physical " << kind << "(\"" << group.name << "\") = {";
        for (std::size_t i = 0; i < group.lists.size(); ++i) out << (i ? ", " : "") << group.lists[i];
        out << "};\n";
    }
    return out.str();
}

std::vector<std::string> flat_geometry_mismatches(
    const MeshProperties& mesh, const std::vector<std::optional<std::size_t>>& material,
    const std::function<std::optional<BoundaryCondition>(const std::array<Vec3, 3>&)>& condition_on,
    const std::function<bool(const std::array<Vec3, 4>&, std::size_t)>& fits) {
    std::vector<std::string> out;
    uint64_t misplaced = 0;
    std::size_t first = 0;
    for (std::size_t e = 0; e < mesh.elements.size(); ++e) {
        const auto& element = mesh.elements[e];
        if (element.material >= material.size() || !material[element.material]) continue;
        std::array<Vec3, 4> tet;
        for (int i = 0; i < 4; ++i) tet[i] = mesh.nodes[element.node[i]];
        if (!fits(tet, *material[element.material]) && misplaced++ == 0) first = e;
    }
    if (misplaced > 0)
        out.push_back(std::to_string(misplaced) + " tets lie outside the region of their material (first: tet " +
                      std::to_string(first) + ", material '" + mesh.materials[mesh.elements[first].material].name + "')");

    uint64_t off_boundary = 0, wrong = 0;
    std::string first_off, first_wrong;
    for (std::size_t b = 0; b < mesh.boundary_elements.size(); ++b) {
        const auto& element = mesh.boundary_elements[b];
        if (element.boundary_condition >= mesh.boundary_conditions.size()) continue;
        std::array<Vec3, 3> triangle;
        for (int i = 0; i < 3; ++i) triangle[i] = mesh.nodes[element.node[i]];
        const auto expected = condition_on(triangle);
        if (!expected) {
            if (off_boundary++ == 0) first_off = std::to_string(b);
            continue;
        }
        const auto& actual = mesh.boundary_conditions[element.boundary_condition];
        if (!same_condition(actual, *expected) && wrong++ == 0)
            first_wrong = "triangle " + std::to_string(b) + " has '" + surface_name(actual) + "', the case '" +
                          surface_name(*expected) + "'";
    }
    if (off_boundary > 0)
        out.push_back(std::to_string(off_boundary) + " boundary triangles do not lie on the boundary of the case (first: triangle " +
                      first_off + ")");
    if (wrong > 0) out.push_back(std::to_string(wrong) + " boundary triangles have the wrong condition (first: " + first_wrong + ")");
    return out;
}

std::vector<std::string> spherical_geometry_mismatches(const MeshProperties& mesh,
                                                       const std::vector<std::optional<std::size_t>>& material,
                                                       const std::vector<std::string>& names,
                                                       const std::vector<std::pair<double, double>>& layers,
                                                       const std::vector<SphereBoundary>& spheres) {
    std::vector<std::string> out;
    double outer = 0;
    for (const auto& [start, end] : layers) outer = std::max(outer, end);
    const double tol = 1e-9 * outer;

    // Tets: within their layer's outer radius; at most half the layer below under its inner
    // radius (a cavity: half its radius); some vertex of each layer on its outer radius.
    std::vector<double> reach(layers.size(), -1);
    uint64_t misplaced = 0;
    std::size_t first = 0;
    for (std::size_t e = 0; e < mesh.elements.size(); ++e) {
        const auto& element = mesh.elements[e];
        if (element.material >= material.size() || !material[element.material]) continue;
        const std::size_t m = *material[element.material];
        std::array<Vec3, 4> tet;
        for (int i = 0; i < 4; ++i) tet[i] = mesh.nodes[element.node[i]];
        const auto [lo, hi] = radius_range(tet);
        const auto [start, end] = layers[m];
        const double below = m > 0 ? 0.5 * (layers[m - 1].second - layers[m - 1].first) : 0.5 * start;
        reach[m] = std::max(reach[m], hi);
        if ((hi > end + tol || lo < start - below) && misplaced++ == 0) first = e;
    }
    if (misplaced > 0)
        out.push_back(std::to_string(misplaced) + " tets lie outside the region of their material (first: tet " +
                      std::to_string(first) + ", material '" + mesh.materials[mesh.elements[first].material].name + "')");
    for (std::size_t m = 0; m < layers.size(); ++m)
        if (reach[m] >= 0 && reach[m] < layers[m].second - tol)
            out.push_back("material '" + names[m] + "' reaches radius " + number(reach[m]) + " instead of " +
                          number(layers[m].second));

    // Boundary triangles: a condition the case puts on a sphere the triangle does not extend
    // past; and for every sphere, some triangle with its condition reaching its radius.
    std::vector<double> sphere_reach(spheres.size(), -1);
    uint64_t wrong = 0;
    std::string first_wrong;
    for (std::size_t b = 0; b < mesh.boundary_elements.size(); ++b) {
        const auto& element = mesh.boundary_elements[b];
        if (element.boundary_condition >= mesh.boundary_conditions.size()) continue;
        const auto& actual = mesh.boundary_conditions[element.boundary_condition];
        std::array<Vec3, 3> triangle;
        for (int i = 0; i < 3; ++i) triangle[i] = mesh.nodes[element.node[i]];
        const double r = radius_range(triangle).second;
        bool ok = false;
        for (std::size_t s = 0; s < spheres.size(); ++s)
            if (same_condition(actual, spheres[s].condition) && r <= spheres[s].radius + tol) {
                ok = true;
                sphere_reach[s] = std::max(sphere_reach[s], r);
            }
        if (!ok && wrong++ == 0)
            first_wrong = "triangle " + std::to_string(b) + " has '" + surface_name(actual) + "' at radius " + number(r);
    }
    if (wrong > 0) out.push_back(std::to_string(wrong) + " boundary triangles have the wrong condition (first: " + first_wrong + ")");
    for (std::size_t s = 0; s < spheres.size(); ++s)
        if (sphere_reach[s] < spheres[s].radius - tol)
            out.push_back("no boundary triangle with '" + surface_name(spheres[s].condition) + "' lies on the sphere of radius " +
                          number(spheres[s].radius));
    return out;
}

